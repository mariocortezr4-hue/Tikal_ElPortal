using System;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEngine;
using UnityEngine.InputSystem;

namespace Tikal.Tests.Editor
{
    public static class SprintBindingAuthoring
    {
        public static void Run()
        {
            try
            {
                const string path = "Assets/_Project/Input/TikalInputActions.inputactions";
                var asset = InputActionAsset.FromJson(File.ReadAllText(path));
                try
                {
                    var sprint = asset.FindAction("Player/Sprint", true);
                    var matches = sprint.bindings.Select((binding, index) => new { binding, index })
                        .Where(item => item.binding.path == "<Gamepad>/rightStickPress").ToArray();
                    if (matches.Length != 1) throw new Exception("Expected exactly one existing right-stick Sprint binding.");
                    string before = asset.ToJson();
                    sprint.ChangeBinding(matches[0].index).WithPath("<Gamepad>/leftStickPress");
                    string after = asset.ToJson();
                    if (after != before.Replace("<Gamepad>/rightStickPress", "<Gamepad>/leftStickPress"))
                        throw new Exception("Unexpected input action changes.");
                    File.WriteAllText(path, after, new System.Text.UTF8Encoding(false));
                }
                finally { UnityEngine.Object.DestroyImmediate(asset); }
                AssetDatabase.ImportAsset(path, ImportAssetOptions.ForceSynchronousImport | ImportAssetOptions.ForceUpdate);
                EditorApplication.delayCall += Complete;
            }
            catch (Exception exception) { Debug.LogException(exception); if (Application.isBatchMode) EditorApplication.Exit(1); }
        }

        static void Complete()
        {
            string wrapper = File.ReadAllText("Assets/_Project/Input/TikalInputActions.cs");
            bool valid = wrapper.Contains("<auto-generated>") && wrapper.Contains("version 1.20.0") &&
                wrapper.Contains("namespace Tikal.Input") && wrapper.Contains("leftStickPress") && !wrapper.Contains("rightStickPress");
            Debug.Log(valid ? "TIKAL_SPRINT_L3_OFFICIALLY_GENERATED" : "Official Sprint wrapper generation failed.");
            if (Application.isBatchMode) EditorApplication.Exit(valid ? 0 : 1);
        }
    }
}
